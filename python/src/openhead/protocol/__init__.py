"""OpenHead protocol models, generated from `protocol/schema`.

`models`, `registry` and `schema.json` are generated by `tools/protocol.py`; this module
only adds helpers on top of them.
"""

from __future__ import annotations

import functools
import json
import time
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from . import models
from .registry import MESSAGE_TYPES, PROTOCOL_VERSION

__all__ = [
    "DEFAULT_PORT",
    "ERROR_CODES",
    "MESSAGE_TYPES",
    "PROTOCOL_VERSION",
    "SERVICE_TYPE",
    "TOPICS",
    "models",
    "now_ms",
    "parse_message",
    "validate",
]

DEFAULT_PORT = 8765
SERVICE_TYPE = "_openhead._tcp.local."
TOPICS = ("imu", "status", "log")
ERROR_CODES = (
    "unauthorized", "unsupported", "busy", "invalid_params", "dev_mode_required", "rate_limited",
)
SCHEMA_PATH = Path(__file__).with_name("schema.json")


def now_ms() -> int:
    return int(time.time() * 1000)


def parse_message(data: dict[str, Any]) -> BaseModel:
    """Validate a decoded JSON message into the model for its `type`.

    Raises `KeyError` for an unknown type and `pydantic.ValidationError` for bad fields.
    """
    return MESSAGE_TYPES[data["type"]].model_validate(data)


@functools.cache
def _validators() -> dict[str, Any]:
    from jsonschema import Draft202012Validator  # only the simulator and tests need it

    bundle = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    return {
        type_: Draft202012Validator({"$defs": bundle["$defs"], "$ref": f"#/$defs/{cls.__name__}"})
        for type_, cls in MESSAGE_TYPES.items()
    }


def validate(data: Any) -> list[str]:
    """Strict check of a message against the JSON Schema. Returns error strings (empty if valid).

    Unlike the models, which ignore unknown fields for forward compatibility, this rejects
    anything the schema does not allow. Requires `jsonschema` (the `[sim]` extra).
    """
    if not isinstance(data, dict) or not isinstance(data.get("type"), str):
        return ["message must be a JSON object with a string 'type'"]
    validator = _validators().get(data["type"])
    if validator is None:
        return [f"unknown message type {data['type']!r}"]
    return [
        f"{'/'.join(map(str, e.absolute_path)) or '<root>'}: {e.message}"
        for e in validator.iter_errors(data)
    ]
